function fisicoDe(materialId: number, color: string): number {
  return LOTES_SIMULADOS.filter(
    (lote) => lote.materialId === materialId && lote.color === color,
  ).reduce((suma, lote) => suma + lote.cantidadDisponible, 0);
}

