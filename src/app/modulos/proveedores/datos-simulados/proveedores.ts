function linea(
  id: number,
  materialId: number,
  precioCompra: number,
  minimoCompra: number,
  plazoDias: number,
  esPrincipal: boolean,
  vigenciaHasta: string | null = '2027-12-31',
  activo = true,
): MaterialProveedor {
  const referencia = MATERIALES_REFERENCIA.find((material) => material.id === materialId);
  return {
    id,
    materialId,
    material: referencia?.nombre ?? `Material ${materialId}`,
    categoria: referencia?.categoria ?? 'Avío',
    critico: referencia?.critico ?? false,
    precioCompra,
    unidadCompra: referencia?.unidadCompra ?? 'pieza',
    minimoCompra,
    plazoDias,
    esPrincipal,
    vigenciaHasta,
    activo,
  };
}

