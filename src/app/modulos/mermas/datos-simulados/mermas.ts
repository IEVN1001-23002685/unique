const CAUSAS_POR_ID = new Map(CAUSAS_SIMULADAS.map((causa) => [causa.id, causa]));

export const MERMAS_SIMULADAS: Merma[] = FILAS.map((fila, indice) => {
  const [
    diasAtras,
    origen,
    procedencia,
    materialId,
    color,
    loteId,
    sku,
    cantidad,
    costoPerdido,
    etapa,
    causaId,
    ordenFolio,
    descripcion,
    evidencia,
  ] = fila;
  const material = materialId === null ? null : MATERIAL_SEED[materialId];
  const producto = sku === null ? null : PRODUCTO_SEED[sku];
  const lotes = loteId === null ? null : `LOTE-2026-${String(loteId).padStart(4, '0')}`;

  return {
    id: indice + 1,
    folio: `MER-2026-${String(31 + indice).padStart(4, '0')}`,
    origen,
    procedencia,
    automatica: procedencia !== 'MANUAL',
    materialId,
    materialCodigo: material?.codigo ?? null,
    materialNombre: material?.nombre ?? null,
    color: color ?? producto?.color ?? null,
    loteId,
    loteFolio: lotes,
    unidadBase: material?.unidadBase ?? (origen === 'PRODUCTO' ? 'pieza' : ''),
    varianteId: producto?.varianteId ?? null,
    sku,
    nombreProducto: producto?.nombre ?? null,
    talla: producto?.talla ?? null,
    cantidad,
    costoPerdido,
    etapa,
    causaId,
    causaNombre: CAUSAS_POR_ID.get(causaId)?.nombre ?? 'Causa no disponible',
    ordenFolio,
    descripcion,
    evidenciaNombre: evidencia,
    registradaPor:
      procedencia === 'MANUAL' ? 'Operativo · demostración' : `${procedencia} · integración`,
    fecha: haceDias(diasAtras),
    esReversion: false,
    reversionDeId: null,
    motivoReversion: null,
  };
});

